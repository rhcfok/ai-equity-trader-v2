-- Watchlist Signal Board — destination table DDL (idempotent).
-- One row per (run_date, symbol); re-runs the same day merge safely on signal_key.
-- RLS enabled, no policies: only the service-role key can read/write.

create table if not exists public."watchlist-signal-board" (
  id bigint generated by default as identity primary key,
  signal_key text unique not null,
  run_date date not null,
  symbol text not null,
  category text,

  -- fresh technical scan (live, this script)
  scan_score numeric(5, 2),
  scan_rsi numeric(6, 2),
  scan_adx numeric(6, 2),
  scan_price numeric(12, 4),
  scan_period text default '3mo',
  scan_missing boolean default false,
  next_earnings date,
  scan_signals jsonb,

  -- jlaw-v2-yahoo (trade-jlaw-v2, jlaw_review_type=yahoo, latest run_date)
  jlaw_yahoo_score int,
  jlaw_yahoo_cls text,
  jlaw_yahoo_stop numeric(12, 4),
  jlaw_yahoo_target numeric(12, 4),
  jlaw_yahoo_run_date date,

  -- jlaw-v2-chart (trade-jlaw-v2, jlaw_review_type=chart, latest run_date)
  jlaw_chart_cls text,
  jlaw_chart_vcp text,
  jlaw_chart_run_date date,

  -- option-flow verdict (flow_verdict_rows, latest verdict_date)
  flow_verdict text,
  flow_tilt numeric(10, 2),
  flow_run_date date,
  flow_stale boolean,

  -- quant2 (quant2_leaderboard, latest run_name)
  quant2_rank int,
  quant2_rules int,
  quant2_grp text,
  quant2_run text,

  -- stldc (trade-stldc-v2, latest run_date)
  stldc_signal text,
  stldc_dir text,
  stldc_score int,
  stldc_structure text,
  stldc_run_date date,

  -- consensus
  votes_bull int default 0,
  votes_bear int default 0,
  votes_neut int default 0,
  consensus text,
  conflict boolean default false,
  chart_veto boolean default false,
  directions jsonb,

  -- run context
  spy_regime text,
  meta jsonb,

  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists wsb_run_date_idx on public."watchlist-signal-board" (run_date);
create index if not exists wsb_symbol_idx on public."watchlist-signal-board" (symbol);
create index if not exists wsb_consensus_idx on public."watchlist-signal-board" (run_date, consensus);

alter table public."watchlist-signal-board" enable row level security;

create or replace function public.wsb_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists wsb_updated_at on public."watchlist-signal-board";
create trigger wsb_updated_at
before update on public."watchlist-signal-board"
for each row execute function public.wsb_touch_updated_at();
